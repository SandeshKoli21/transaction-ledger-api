// Input validation. Every check returns a clear 400 VALIDATION_ERROR listing what is wrong.
const { AppError } = require('./errors');

const isStr = (v) => typeof v === 'string' && v.trim().length > 0;

function checkReferenceId(ref, errors) {
  if (!isStr(ref)) errors.push('reference_id is required');
  else if (ref.trim().length > 100) errors.push('reference_id must be at most 100 characters');
}

function fail(errors) {
  if (errors.length) throw new AppError(400, 'VALIDATION_ERROR', 'Invalid request data', { errors });
}

function checkAmount(amount, errors) {
  if (typeof amount !== 'number' || !Number.isFinite(amount)) errors.push('amount must be a number');
  else if (amount <= 0) errors.push('amount must be greater than 0');
  else if (Math.abs(amount * 100 - Math.round(amount * 100)) > 1e-6) errors.push('amount can have at most 2 decimal places');
  else if (amount > 1e12) errors.push('amount is too large');
}

function checkOptionalDescription(d, errors) {
  if (d !== undefined && d !== null && typeof d !== 'string') errors.push('description must be a string');
  else if (typeof d === 'string' && d.length > 500) errors.push('description must be at most 500 characters');
}

function account(body) {
  const errors = [];
  if (!isStr(body.name)) errors.push('name is required');
  else if (body.name.length > 200) errors.push('name must be at most 200 characters');
  if ('balance' in body) errors.push('balance cannot be set by the client; it always starts at 0');
  if ('id' in body || 'created_at' in body) errors.push('id and created_at are generated by the system');
  fail(errors);
  return { name: body.name.trim() };
}

function transaction(body) {
  const errors = [];
  if (!['credit', 'debit'].includes(body.type)) errors.push("type must be either 'credit' or 'debit'");
  checkAmount(body.amount, errors);
  checkReferenceId(body.reference_id, errors);
  checkOptionalDescription(body.description, errors);
  fail(errors);
  return { type: body.type, amount: body.amount, description: body.description ?? null, reference_id: body.reference_id.trim() };
}

function transfer(body) {
  const errors = [];
  if (!isStr(body.from_account_id)) errors.push('from_account_id is required');
  if (!isStr(body.to_account_id)) errors.push('to_account_id is required');
  if (isStr(body.from_account_id) && body.from_account_id === body.to_account_id) errors.push('cannot transfer to the same account');
  checkAmount(body.amount, errors);
  checkReferenceId(body.reference_id, errors);
  checkOptionalDescription(body.description, errors);
  fail(errors);
  return { ...body, description: body.description ?? null, reference_id: body.reference_id.trim() };
}

function pagination(query) {
  const errors = [];
  const out = { type: undefined, page: 1, limit: 10 };
  const intParam = (name, max) => {
    const raw = query.get(name);
    if (raw === null) return undefined;
    if (!/^\d+$/.test(raw) || Number(raw) < 1) { errors.push(`${name} must be a positive integer`); return undefined; }
    if (max && Number(raw) > max) { errors.push(`${name} must be at most ${max}`); return undefined; }
    return Number(raw);
  };
  out.page = intParam('page', 1e6) ?? 1;
  out.limit = intParam('limit', 100) ?? 10;
  const type = query.get('type');
  if (type !== null) {
    if (!['credit', 'debit'].includes(type)) errors.push("type must be either 'credit' or 'debit'");
    else out.type = type;
  }
  fail(errors);
  return out;
}

module.exports = { account, transaction, transfer, pagination };
